export function isRouteAllowedForRole(role: string, path: string): boolean {
  const allowed = ROLE_ROUTE_PERMISSIONS[role as Role];
  if (!allowed) return true;
  return allowed.some((prefix) => path === prefix || path.startsWith(`${prefix}/`));
}

export function hasPermission(userPermissions: string[] = [], requiredPermission: Permission): boolean {
  if (userPermissions.includes('*') || userPermissions.includes(Permission.MANAGE_SETTINGS)) {
    return true;
  }
  return userPermissions.includes(requiredPermission);
}
